export const TEMPLATES: InvitationTemplate[] = BASE_TEMPLATES.map((t) => {
  const music = TEMPLATE_MUSIC_CONFIGS[t.id];
  const audioPath = music?.audioPath || '/assets/audio/best/Classic.mp3';
  return {
    ...t,
    audioPath,
    suggestedMusic: music?.trackTitle || t.suggestedMusic,
    musicMood: music?.mood,
    musicRationale: music?.rationale,
  };
});

export function getTemplateById(id: string): InvitationTemplate {
  const found = TEMPLATES.find((t) => t.id === id);
  return found || TEMPLATES[0];
}

export function getTemplatesByCategory(category: string): InvitationTemplate[] {
  if (category === 'All') return TEMPLATES;
  return TEMPLATES.filter((t) => t.category === category);
}
